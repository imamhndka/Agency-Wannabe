function t(key, replacements = {}) {
    let str = (translations[currentLang] && translations[currentLang][key]) || translations['id'][key] || key;
    if (typeof str === 'string') {
        Object.keys(replacements).forEach(r => { str = str.replace(`{${r}}`, replacements[r]); });
    }
    return str;
}

function setLanguage(lang) {
    window.currentLang = lang;
    localStorage.setItem('3s_agency_lang', lang);
    applyLanguage();
    refreshActiveUI();
}

function applyLanguage() {
    const btnId = document.getElementById('lang-btn-id');
    const btnEn = document.getElementById('lang-btn-en');
    if (currentLang === 'id') {
        btnId.className = 'px-2 py-1 sm:px-2.5 rounded-lg transition-all bg-white dark:bg-gray-800 text-blue-600 shadow-sm font-bold';
        btnEn.className = 'px-2 py-1 sm:px-2.5 rounded-lg transition-all hover:text-gray-900 font-medium';
    } else {
        btnEn.className = 'px-2 py-1 sm:px-2.5 rounded-lg transition-all bg-white dark:bg-gray-800 text-blue-600 shadow-sm font-bold';
        btnId.className = 'px-2 py-1 sm:px-2.5 rounded-lg transition-all hover:text-gray-900 font-medium';
    }

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key) el.innerText = t(key);
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (key) el.setAttribute('placeholder', t(key));
    });

    if (window.syncState) setSyncBadge(window.syncState);

    // Refresh header titles
    const activeNav = document.getElementById(`nav-${window.currentTab}`);
    if (activeNav) {
        const titleSpan = activeNav.querySelector('span');
        if (titleSpan) document.getElementById('page-title').innerText = titleSpan.innerText;
    }
}
